"""Generate typed Python classes from a domain pack.

See docs/ONTOLOGY_TYPED_CLIENT.md. The output is one module that imports only
the standard library. Each object type becomes a frozen dataclass whose
``from_instance`` checks one instance dictionary, as returned by the ontology
library, against the pack the module was generated from.

A pack is untrusted input and the output is source code. Pack text reaches the
output only as an ``ascii()`` literal or as an identifier that passed
``_identifier``. Names, descriptions and units are not written out at all. A
name that cannot be used is refused, never rewritten.

Print a module with ``python -m agora.ontology.typed pack.yaml``.
"""

from __future__ import annotations

import builtins
import keyword
import re
import sys
from decimal import Decimal
from typing import Any, Sequence

from .loader import load_domain_pack
from .registry import SENSITIVITY_LEVELS, ObjectType, OntologyError, OntologyPack, PropertyType


GENERATOR_VERSION = "1"

# logical data type -> (annotation, converter in the generated module)
_TYPES = {
    "string": ("str", "_text"),
    "identifier": ("str", "_text"),
    "enum": ("str", "_text"),
    "integer": ("int", "_integer"),
    "boolean": ("bool", "_boolean"),
    "decimal": ("_Decimal", "_decimal"),
    "date": ("_date", "_day"),
    "timestamp": ("_datetime", "_timestamp"),
}
_CLASS_NAME = re.compile(r"[A-Z][A-Za-z0-9_]*")
_FIELD_NAME = re.compile(r"[A-Za-z][A-Za-z0-9_]*")
# Module-level names of the output. Builtins are refused too: the helpers use them.
_RESERVED_CLASSES = frozenset(dir(builtins)) | {
    "GENERATOR_VERSION", "PACK_ID", "PACK_SCHEMA_VERSION", "PACK_FINGERPRINT", "OBJECT_TYPES",
    "InstanceError", "Provenance",
}
# ``classmethod``, ``str``, ``int`` and ``bool`` would shadow names that the class
# body or its annotations use. The rest are members of every generated class.
_RESERVED_FIELDS = frozenset({
    "classmethod", "str", "int", "bool", "provenance", "from_instance", "TYPE_ID", "TYPE_VERSION",
})

_HEADER = '''\
"""Typed ontology objects. Generated by agora.ontology.typed; do not edit.

``from_instance`` checks the shape and values of one instance dictionary. It does
not authenticate the dictionary or apply any access policy. Property values are
left out of ``repr``; they are still readable as attributes.
"""

from __future__ import annotations

import re as _re
from collections.abc import Mapping as _Mapping
from dataclasses import dataclass as _dataclass, field as _field
from datetime import date as _date, datetime as _datetime, timezone as _timezone
from decimal import Decimal as _Decimal
'''

_RUNTIME = '''\
_RANK = {"public": 0, "internal": 1, "personal": 2, "sensitive": 3}
# The form tabular ingestion stores: no spaces, underscores or exponent.
_PLAIN_DECIMAL = _re.compile(r"-?[0-9]+(?:\.[0-9]+)?")


class InstanceError(ValueError):
    """An instance does not fit the generated type. Messages never carry values."""


@_dataclass(frozen=True)
class Provenance:
    record_key: str
    import_id: str
    row_id: str
    dataset_id: str
    binding_id: str
    binding_version: str
    binding_fingerprint: str
    file_sha256: str | None
    source_registry_id: str | None
    property_sensitivity: tuple[tuple[str, str], ...]


def _text(value):
    if type(value) is not str:
        raise ValueError
    return value


def _integer(value):
    if type(value) is not int:
        raise ValueError
    return value


def _boolean(value):
    if type(value) is not bool:
        raise ValueError
    return value


def _decimal(value):
    # A float is refused: it may already have lost digits.
    if type(value) is int:
        return _Decimal(value)
    if not _PLAIN_DECIMAL.fullmatch(_text(value)):
        raise ValueError
    return _Decimal(value)


def _day(value):
    parsed = _date.fromisoformat(_text(value))
    if parsed.isoformat() != value:
        raise ValueError
    return parsed


def _timestamp(value):
    parsed = _datetime.fromisoformat(_text(value))
    if parsed.tzinfo is None:
        raise ValueError
    try:
        converted = parsed.astimezone(_timezone.utc)
    except OverflowError:
        raise ValueError from None
    if converted.isoformat() != value:
        raise ValueError
    return converted


def _allowed(value, converted, choices, convert):
    if convert is _decimal:
        return any(_Decimal(choice) == converted for choice in choices)
    return any(type(choice) is type(value) and choice == value for choice in choices)


def _read(instance, type_id, type_version, spec):
    """Check one instance and return (converted values by field, provenance)."""
    if not isinstance(instance, _Mapping):
        raise InstanceError("instance must be a mapping")
    if instance.get("object_type_id") != type_id or instance.get("object_type_version") != type_version:
        raise InstanceError("instance is not of this object type and version")
    expected = {property_id for _name, property_id, *_rest in spec}
    values = instance.get("property_values")
    if not isinstance(values, _Mapping) or set(values) != expected:
        raise InstanceError("property_values must hold exactly the properties of this type")
    levels = instance.get("property_sensitivity")
    if not isinstance(levels, _Mapping) or set(levels) != expected:
        raise InstanceError("property_sensitivity must classify exactly the properties of this type")
    result = {}
    sensitivity = []
    for name, property_id, convert, nullable, choices, declared in spec:
        level = levels[property_id]
        if type(level) is not str or level not in _RANK or _RANK[level] < _RANK[declared]:
            raise InstanceError(f"sensitivity of {property_id} is unknown or below the declared level")
        sensitivity.append((property_id, level))
        value = values[property_id]
        if value is None:
            if not nullable:
                raise InstanceError(f"{property_id} is not nullable")
            result[name] = None
            continue
        try:
            converted = convert(value)
        except ValueError:
            # No chained cause: the standard library's message can repeat the value.
            raise InstanceError(f"{property_id} does not have its declared data type") from None
        if choices and not _allowed(value, converted, choices, convert):
            raise InstanceError(f"{property_id} is not an allowed value")
        result[name] = converted
    details = {}
    for key in ("record_key", "import_id", "row_id", "dataset_id", "binding_id",
                "binding_version", "binding_fingerprint"):
        value = instance.get(key)
        if type(value) is not str or not value:
            raise InstanceError(f"instance lacks the provenance field {key}")
        details[key] = value
    for key in ("file_sha256", "source_registry_id"):
        value = instance.get(key)
        if value is not None and type(value) is not str:
            raise InstanceError(f"provenance field {key} must be text or null")
        details[key] = value
    return result, Provenance(**details, property_sensitivity=tuple(sensitivity))
'''


def _identifier(name: str, pattern: re.Pattern[str], reserved: frozenset[str], source_id: str) -> str:
    if not pattern.fullmatch(name) or keyword.iskeyword(name) or name in reserved:
        raise OntologyError(f"no usable Python name for {ascii(source_id)}")
    return name


def _literal(value: Any) -> str:
    try:
        return ascii(value)
    except ValueError as exc:  # an integer too long to print
        raise OntologyError("an allowed value cannot be written as a Python literal") from exc


def _choices(prop: PropertyType) -> str:
    # A null entry says nothing here: nullability alone decides whether null passes.
    values = [value for value in prop.allowed_values if value is not None]
    if not values and prop.allowed_values:
        raise OntologyError(f"allowed_values of {ascii(prop.property_id)} lists only null")
    if prop.data_type == "decimal":
        values = [str(Decimal(str(value))) for value in values]
    return "(" + "".join(f"{_literal(value)}, " for value in values) + ")"


def _class_source(item: ObjectType, name: str, properties: dict[str, PropertyType]) -> str:
    fields: list[str] = []
    spec: list[str] = []
    used: set[str] = set()
    for property_id in item.properties:
        prop = properties[property_id]
        if prop.data_type not in _TYPES:
            raise OntologyError(f"no typed form for the data type of {ascii(property_id)}")
        if prop.sensitivity not in SENSITIVITY_LEVELS:
            raise OntologyError(f"unknown sensitivity on {ascii(property_id)}")
        local = property_id.partition(":")[2].rpartition(".")[2]
        field_name = _identifier(local, _FIELD_NAME, _RESERVED_FIELDS, property_id)
        if field_name in used:
            raise OntologyError(f"two properties of {ascii(item.type_id)} give the same Python name")
        used.add(field_name)
        annotation, converter = _TYPES[prop.data_type]
        if prop.nullable:
            annotation += " | None"
        fields.append(f"    {field_name}: {annotation} = _field(repr=False)\n")
        spec.append(
            f"            ({_literal(field_name)}, {_literal(property_id)}, {converter}, "
            f"{prop.nullable is True}, {_choices(prop)}, {_literal(prop.sensitivity)}),\n"
        )
    return (
        "@_dataclass(frozen=True)\n"
        f"class {name}:\n"
        f"    TYPE_ID = {_literal(item.type_id)}\n"
        f"    TYPE_VERSION = {_literal(item.version)}\n"
        "\n"
        "    provenance: Provenance\n"
        + "".join(fields)
        + "\n"
        "    @classmethod\n"
        f"    def from_instance(cls, instance: _Mapping) -> {name}:\n"
        "        values, provenance = _read(instance, cls.TYPE_ID, cls.TYPE_VERSION, (\n"
        + "".join(spec)
        + "        ))\n"
        "        return cls(provenance=provenance, **values)\n"
    )


def generate_python_types(pack: OntologyPack) -> str:
    """Return the source of a typed module for ``pack``. The same pack gives the same text."""
    if not isinstance(pack, OntologyPack):
        raise OntologyError("generate_python_types needs a parsed OntologyPack")
    properties = {item.property_id: item for item in pack.property_types}
    classes: list[str] = []
    registry: list[str] = []
    used: set[str] = set()
    for item in pack.object_types:
        name = _identifier(item.type_id.partition(":")[2], _CLASS_NAME, _RESERVED_CLASSES, item.type_id)
        if name in used:
            raise OntologyError("two object types give the same Python class name")
        used.add(name)
        classes.append(_class_source(item, name, properties))
        registry.append(f"    ({_literal(item.type_id)}, {_literal(item.version)}): {name},\n")
    constants = (
        f"GENERATOR_VERSION = {_literal(GENERATOR_VERSION)}\n"
        f"PACK_ID = {_literal(pack.pack_id)}\n"
        f"PACK_SCHEMA_VERSION = {_literal(pack.schema_version)}\n"
        f"PACK_FINGERPRINT = {_literal(pack.fingerprint)}\n"
    )
    blocks = [_HEADER, constants, _RUNTIME, *classes, "OBJECT_TYPES = {\n" + "".join(registry) + "}\n"]
    return "\n\n".join(blocks)


def main(argv: Sequence[str] | None = None) -> int:
    """Print the typed module for one pack. Exit 0: printed. 2: the pack could not be used."""
    arguments = list(sys.argv[1:] if argv is None else argv)
    if len(arguments) != 1 or arguments[0].startswith("-"):
        print("usage: python -m agora.ontology.typed pack.yaml", file=sys.stderr)
        return 2
    try:
        source = generate_python_types(load_domain_pack(arguments[0]))
    except OntologyError as exc:
        print(f"error: {exc}", file=sys.stderr)
        return 2
    sys.stdout.write(source)
    return 0


if __name__ == "__main__":
    raise SystemExit(main())
